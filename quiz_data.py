Q1_TO_RESULT = ["site", "bot", "channel", "social", "plan", "plan"]


def pick_result(answers):
    """answers — список индексов выбранных вариантов по каждому вопросу."""
    totals = {key: 0 for key in RESULTS}
    for q_index, opt_index in enumerate(answers):
        for key, pts in SCORES.get((q_index, opt_index), {}).items():
            totals[key] += pts
    best = max(totals.values())
    leaders = [k for k, v in totals.items() if v == best]
    if len(leaders) == 1:
        return leaders[0]
    preferred = Q1_TO_RESULT[answers[0]]
    return preferred if preferred in leaders else leaders[0]


def summary(answers):
    lines = [
        f"• {QUESTIONS[i]['text']} — {QUESTIONS[i]['options'][a]}"
        for i, a in enumerate(answers)
    ]
    return "\n".join(lines)


def result_message(answers):
    title, text = RESULTS[pick_result(answers)]
    return (
        f"Рекомендуемое направление: {title}\n\n{text}\n\n"
        f"Ваши ответы:\n{summary(answers)}\n\n{CTA_TEXT}"
    )
